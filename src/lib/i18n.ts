const messages: Record<Locale, Record<Key, string>> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW }
export function translate(locale: Locale, key: Key) {
  return messages[locale][key]
}
export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'zh-CN' || value === 'zh-TW'
}
export function localeFromLanguages(languages: readonly string[]): Locale {
  for (const value of languages) {
    const language = value.toLowerCase()
    if (language === 'en' || language.startsWith('en-'))
      return 'en'
    if (!/^zh(?:-|$)/.test(language))
      continue
    if (/(?:-|^)(?:tw|hk|mo|hant)(?:-|$)/.test(language))
      return 'zh-TW'
    return 'zh-CN'
  }
  return 'en'
}
